from iocs.base import Artifact, IOC, ScriptCheck

firewall_random_admins = IOC(
    name="firewall_random_admins",
    description="Pool-driven admin accounts added to firewall (up to 12 users)",
    category="users",
    difficulty=1,
    os="firewall",
    check=ScriptCheck(script="check_scripts/firewall/firewall_random_admins_check.sh"),
    discovery="Use either the GUI or shell to find extraneous users and then remove",
    deploy_script="deploy_scripts/firewall/firewall_random_admins_deploy.sh",
    remediate_script="remediate_scripts/firewall/firewall_random_admins_remediate.sh",
    # Up to 12 pool-driven usernames injected as space-separated C3R_USER_NAMES
    pooled_name_lists=[("USER_NAMES", "user", 12)],
    sa_highlight={},
    detection_steps=[
        "List all local users on the firewall via the pfSense GUI: System → User Manager → Users. "
        "Look for unexpected accounts (check C3rberus SA 'local_users_groups' tab for highlights).",
        "From the shell: `pw usershow -a | awk -F: '{print $1}'` to list all accounts. "
        "Confirm each suspicious account has a login shell and `admins` group membership: "
        "`pw usershow <username>` — the shell field (column 10) should be `/bin/sh` and "
        "`groups <username>` should include `admins`.",
        "Verify the password equals the username (the IOC's seeded credential): "
        "for bcrypt hashes the check script falls back to shell+group membership as evidence.",
    ],
    remediation_steps=[
        "Remount the pfSense root filesystem read-write before making changes: "
        "`/sbin/mount -uw /`",
        "Delete each malicious account: `pw userdel <username> -r`. "
        "Repeat for every IOC account (check the cron entry or C3rberus task details for the full list).",
        "Verify removal: `pw usershow -a` should no longer show the removed accounts, "
        "and the pfSense GUI (System → User Manager → Users) should confirm they are gone.",
    ],
    artifacts=[
        Artifact(
            dynamic=True,
            description="Up to 12 pool-driven local pfSense accounts; password == username; shell /bin/sh; member of admins group",
        ),
        Artifact(
            path="/etc/master.passwd",
            description="FreeBSD master password file — contains hashed entries for every created IOC account",
        ),
        Artifact(
            path="/etc/passwd",
            description="World-readable shadow of master.passwd regenerated by pw after each user creation",
        ),
    ],
)
